----------------------------------- 0. BORRADO PREVIO ---------------------------------
-- CASCADE CONSTRAINTS elimina también las llaves foráneas; por eso el orden no importa.
BEGIN
    FOR t IN (SELECT table_name
              FROM user_tables
              WHERE table_name IN ('FACT_RESERVA', 'DIM_TIEMPO', 'DIM_CANCHA', 'DIM_USUARIO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

----------------------------------- 1. DIM_USUARIO ------------------------------------
-- Autonomous Database trabaja en UTC; los valores por defecto se guardan en hora de Bogotá.
CREATE TABLE dim_usuario (
    id_usuario       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    documento        VARCHAR2(20)  NOT NULL,
    nombre           VARCHAR2(60)  NOT NULL,
    apellido         VARCHAR2(60)  NOT NULL,
    correo           VARCHAR2(100) NOT NULL,
    telefono         VARCHAR2(20),
    tipo_usuario     VARCHAR2(20)  NOT NULL,
    fecha_registro   DATE          DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Bogota' AS DATE) NOT NULL,
    estado_usuario   VARCHAR2(20)  DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT pk_dim_usuario        PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_documento  UNIQUE (documento),
    CONSTRAINT uq_usuario_correo     UNIQUE (correo),
    CONSTRAINT ck_usuario_documento  CHECK (REGEXP_LIKE(documento, '^[A-Za-z0-9]{5,20}$')),
    CONSTRAINT ck_usuario_nombre     CHECK (TRIM(nombre) IS NOT NULL),
    CONSTRAINT ck_usuario_apellido   CHECK (TRIM(apellido) IS NOT NULL),
    CONSTRAINT ck_usuario_correo     CHECK (REGEXP_LIKE(correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$') AND correo = LOWER(correo)),
    -- Opcional; si se informa: un '+' inicial opcional y de 7 a 15 dígitos.
    CONSTRAINT ck_usuario_telefono   CHECK (telefono IS NULL OR REGEXP_LIKE(telefono, '^\+?[0-9]{7,15}$')),
    CONSTRAINT ck_usuario_tipo       CHECK (tipo_usuario IN ('ESTUDIANTE', 'MIEMBRO', 'EXTERNO')),
    CONSTRAINT ck_usuario_estado     CHECK (estado_usuario IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);

----------------------------------- 2. DIM_CANCHA -------------------------------------
CREATE TABLE dim_cancha (
    id_cancha        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR2(60)  NOT NULL,
    deporte          VARCHAR2(30)  NOT NULL,
    sede             VARCHAR2(60)  NOT NULL,
    superficie       VARCHAR2(30)  NOT NULL,
    capacidad        NUMBER        NOT NULL,
    precio_hora      NUMBER(10,2)  NOT NULL,
    estado_cancha    VARCHAR2(20)  DEFAULT 'DISPONIBLE' NOT NULL,

    CONSTRAINT pk_dim_cancha         PRIMARY KEY (id_cancha),
    -- Una sede no puede tener dos canchas con el mismo nombre.
    CONSTRAINT uq_cancha_nombre_sede UNIQUE (nombre, sede),
    CONSTRAINT ck_cancha_nombre      CHECK (TRIM(nombre) IS NOT NULL),
    CONSTRAINT ck_cancha_sede        CHECK (TRIM(sede) IS NOT NULL),
    -- Deportes que ofrece el club: pádel, fútbol 7x7 y 9x9, vóley en arena y basket 3x3.
    CONSTRAINT ck_cancha_deporte     CHECK (deporte IN ('PADEL', 'FUTBOL_7X7', 'FUTBOL_9X9', 'VOLEY_ARENA', 'BASKET_3X3')),
    CONSTRAINT ck_cancha_superficie  CHECK (superficie IN ('SINTETICA', 'CESPED', 'ARENA', 'ACRILICA', 'CEMENTO')),
    CONSTRAINT ck_cancha_capacidad   CHECK (capacidad > 0 AND capacidad = TRUNC(capacidad)),
    CONSTRAINT ck_cancha_precio      CHECK (precio_hora >= 0),
    CONSTRAINT ck_cancha_estado      CHECK (estado_cancha IN ('DISPONIBLE', 'MANTENIMIENTO', 'CERRADA'))
);

----------------------------------- 3. DIM_TIEMPO -------------------------------------
-- Cada fila es un bloque reservable de una hora. El club atiende de 06:00 a 22:00,
-- por lo que el último bloque inicia a las 21:00.
CREATE TABLE dim_tiempo (
    id_tiempo        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha            DATE          NOT NULL,
    hora_inicio      NUMBER(2)     NOT NULL,
    anio             NUMBER(4)     NOT NULL,
    mes              NUMBER(2)     NOT NULL,
    dia_semana       VARCHAR2(10)  NOT NULL,
    franja           VARCHAR2(10)  NOT NULL,
    es_festivo       VARCHAR2(2)   DEFAULT 'NO' NOT NULL,

    CONSTRAINT pk_dim_tiempo         PRIMARY KEY (id_tiempo),
    -- UNIQUE compuesto: un mismo día no puede repetir la misma hora de inicio.
    CONSTRAINT uq_tiempo_fecha_hora  UNIQUE (fecha, hora_inicio),
    CONSTRAINT ck_tiempo_fecha_dia   CHECK (fecha = TRUNC(fecha)),
    CONSTRAINT ck_tiempo_hora        CHECK (hora_inicio BETWEEN 6 AND 21),
    CONSTRAINT ck_tiempo_anio        CHECK (anio = EXTRACT(YEAR FROM fecha)),
    CONSTRAINT ck_tiempo_mes         CHECK (mes = EXTRACT(MONTH FROM fecha)),
    CONSTRAINT ck_tiempo_dia_semana  CHECK (dia_semana IN ('LUNES', 'MARTES', 'MIERCOLES', 'JUEVES', 'VIERNES', 'SABADO', 'DOMINGO')),
    -- El día de la semana debe corresponder a la fecha (el 03/01/2000 fue lunes).
    -- Se calcula con aritmética de fechas para no depender del idioma de la sesión.
    CONSTRAINT ck_tiempo_dia_fecha   CHECK (dia_semana = CASE MOD(fecha - DATE '2000-01-03', 7)
                                                          WHEN 0 THEN 'LUNES'     WHEN 1 THEN 'MARTES'
                                                          WHEN 2 THEN 'MIERCOLES' WHEN 3 THEN 'JUEVES'
                                                          WHEN 4 THEN 'VIERNES'   WHEN 5 THEN 'SABADO'
                                                          ELSE 'DOMINGO' END),
    CONSTRAINT ck_tiempo_franja      CHECK (franja IN ('MANANA', 'TARDE', 'NOCHE')),
    CONSTRAINT ck_tiempo_franja_hora CHECK ((franja = 'MANANA' AND hora_inicio BETWEEN 6  AND 11)
                                         OR (franja = 'TARDE'  AND hora_inicio BETWEEN 12 AND 17)
                                         OR (franja = 'NOCHE'  AND hora_inicio BETWEEN 18 AND 21)),
    CONSTRAINT ck_tiempo_festivo     CHECK (es_festivo IN ('SI', 'NO'))
);

----------------------------------- 4. FACT_RESERVA -----------------------------------
-- Ciclo de vida de la reserva (estado_reserva):
--   PENDIENTE : solicitud creada, aún sin confirmar.          Ocupa el bloque.
--   RESERVADA : confirmada; cupo asegurado, falta el pago.    Ocupa el bloque.
--   PAGADA    : reserva pagada.                               Ocupa el bloque.
--   VENCIDA   : no se confirmó o no se pagó a tiempo.         Libera el bloque.
--   CANCELADA : cancelada por el usuario o el administrador.  Libera el bloque.
-- id_tiempo es el bloque de INICIO; la reserva ocupa duracion_horas bloques seguidos.
-- valor_total se guarda en la reserva para conservar el precio histórico.
CREATE TABLE fact_reserva (
    id_reserva       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       NUMBER        NOT NULL,
    id_cancha        NUMBER        NOT NULL,
    id_tiempo        NUMBER        NOT NULL,
    duracion_horas   NUMBER(1)     NOT NULL,
    valor_total      NUMBER(10,2)  NOT NULL,
    metodo_pago      VARCHAR2(20)  NOT NULL,
    estado_reserva   VARCHAR2(20)  DEFAULT 'PENDIENTE' NOT NULL,
    calificacion     NUMBER(1),
    fecha_creacion   DATE          DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Bogota' AS DATE) NOT NULL,

    CONSTRAINT pk_fact_reserva         PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_usuario      FOREIGN KEY (id_usuario) REFERENCES dim_usuario (id_usuario),
    CONSTRAINT fk_reserva_cancha       FOREIGN KEY (id_cancha)  REFERENCES dim_cancha  (id_cancha),
    CONSTRAINT fk_reserva_tiempo       FOREIGN KEY (id_tiempo)  REFERENCES dim_tiempo  (id_tiempo),
    CONSTRAINT ck_reserva_duracion     CHECK (duracion_horas BETWEEN 1 AND 3),
    CONSTRAINT ck_reserva_valor        CHECK (valor_total >= 0),
    CONSTRAINT ck_reserva_metodo       CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'NEQUI')),
    CONSTRAINT ck_reserva_estado       CHECK (estado_reserva IN ('PENDIENTE', 'RESERVADA', 'PAGADA', 'VENCIDA', 'CANCELADA')),
    CONSTRAINT ck_reserva_calificacion CHECK (calificacion BETWEEN 1 AND 5),
    -- La calificación solo existe cuando la reserva está PAGADA; en otro estado es NULL.
    CONSTRAINT ck_reserva_calif_estado CHECK (calificacion IS NULL OR estado_reserva = 'PAGADA')
);

-- UNIQUE condicional: una cancha no puede tener dos reservas ACTIVAS que inicien en el
-- mismo bloque. Las reservas CANCELADA o VENCIDA devuelven NULL en ambas expresiones;
-- Oracle no indexa filas con todas las claves en NULL, así que liberan el bloque.
-- Un UNIQUE normal impediría volver a reservar una hora que alguien canceló.
-- Las reservas de 2 o 3 horas que se cruzan con otra se validan en la aplicación.
CREATE UNIQUE INDEX uq_reserva_cancha_bloque ON fact_reserva (
    CASE WHEN estado_reserva IN ('PENDIENTE', 'RESERVADA', 'PAGADA') THEN id_cancha END,
    CASE WHEN estado_reserva IN ('PENDIENTE', 'RESERVADA', 'PAGADA') THEN id_tiempo END
);

-- Índices sobre las llaves foráneas: aceleran los JOIN y los reportes de la aplicación.
CREATE INDEX ix_reserva_usuario ON fact_reserva (id_usuario);
CREATE INDEX ix_reserva_cancha  ON fact_reserva (id_cancha);
CREATE INDEX ix_reserva_tiempo  ON fact_reserva (id_tiempo);

----------------------------------- 5. PERMISOS PARA LA APLICACIÓN --------------------
-- APP_RESERVAS solo puede leer, insertar y actualizar. No tiene DELETE ni DDL:
-- desde la aplicación nadie puede borrar reservas, usuarios ni tablas.
-- Al re-ejecutar este script las tablas se recrean, por eso los permisos van aquí.
GRANT SELECT, INSERT, UPDATE ON dim_usuario  TO app_reservas;
GRANT SELECT, UPDATE         ON dim_cancha   TO app_reservas;
GRANT SELECT                 ON dim_tiempo   TO app_reservas;
GRANT SELECT, INSERT, UPDATE ON fact_reserva TO app_reservas;
